-- Q5b: AUM by TYPE (End-of-Month snapshot, Tỷ VND)
SELECT
  GRASS_DATE,
  TYPE,
  ROUND(SUM(COALESCE(balance, 0)) / 1e9, 0) AS aum_B,
  COUNT(DISTINCT REGEXP_EXTRACT(USER_ID, r'\d+')) AS users
FROM `momovn-prod.BU_FI.mart_ttt_daily_user_record`
WHERE GRASS_DATE IN (
  LAST_DAY(DATE '2025-01-01'), LAST_DAY(DATE '2025-06-01'),
  LAST_DAY(DATE '2025-12-01'), LAST_DAY(DATE '2026-01-01'),
  LAST_DAY(DATE '2026-02-01'), DATE '2026-03-09'
)
GROUP BY GRASS_DATE, TYPE
ORDER BY GRASS_DATE, TYPE
