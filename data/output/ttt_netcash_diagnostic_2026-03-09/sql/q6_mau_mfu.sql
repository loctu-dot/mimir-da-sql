-- Q6: MAU / MFU Monthly
SELECT
  FORMAT_DATE('%Y-%m', GRASS_DATE) AS month,
  COUNT(DISTINCT CASE WHEN MAU_TYPE != '0.Churn' THEN REGEXP_EXTRACT(USER_ID, r'\d+') END) AS mau,
  COUNT(DISTINCT CASE WHEN MFU_TYPE != '0.Churn' THEN REGEXP_EXTRACT(USER_ID, r'\d+') END) AS mfu,
  COUNT(DISTINCT CASE WHEN MAU_TYPE = '1.New' THEN REGEXP_EXTRACT(USER_ID, r'\d+') END) AS mau_new,
  COUNT(DISTINCT CASE WHEN MAU_TYPE = '3.Reactive' THEN REGEXP_EXTRACT(USER_ID, r'\d+') END) AS mau_reactive
FROM `momovn-prod.BU_FI.mart_ttt_daily_user_record`
WHERE GRASS_DATE BETWEEN '2025-01-01' AND '2026-03-09'
GROUP BY month
ORDER BY month
