-- Q8: Balance Group Distribution (Individual, End-of-Month)
SELECT
  GRASS_DATE,
  SUM(CASE WHEN MFU_TYPE = '0.Churn' THEN 1 ELSE 0 END) AS grp_churn,
  SUM(CASE WHEN balance > 0 AND balance <= 300000 THEN 1 ELSE 0 END) AS grp_0_300k,
  SUM(CASE WHEN balance > 300000 AND balance <= 3000000 THEN 1 ELSE 0 END) AS grp_300k_3M,
  SUM(CASE WHEN balance > 3000000 AND balance <= 30000000 THEN 1 ELSE 0 END) AS grp_3_30M,
  SUM(CASE WHEN balance > 30000000 AND balance <= 50000000 THEN 1 ELSE 0 END) AS grp_30_50M,
  SUM(CASE WHEN balance > 50000000 AND balance <= 100000000 THEN 1 ELSE 0 END) AS grp_50_100M,
  SUM(CASE WHEN balance > 100000000 THEN 1 ELSE 0 END) AS grp_gt100M
FROM `momovn-prod.BU_FI.mart_ttt_daily_user_record`
WHERE IS_MP = 'Individual'
  AND GRASS_DATE IN (
    LAST_DAY(DATE '2025-01-01'), LAST_DAY(DATE '2025-03-01'),
    LAST_DAY(DATE '2025-06-01'), LAST_DAY(DATE '2025-09-01'),
    LAST_DAY(DATE '2025-12-01'), LAST_DAY(DATE '2026-01-01'),
    LAST_DAY(DATE '2026-02-01'), DATE '2026-03-09'
  )
GROUP BY GRASS_DATE
ORDER BY GRASS_DATE
