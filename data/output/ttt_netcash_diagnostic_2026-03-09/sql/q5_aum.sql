-- Q5: AUM End-of-Month (Tỷ VND)
SELECT
  GRASS_DATE,
  ROUND(SUM(COALESCE(balance, 0)) / 1e9, 0) AS total_aum_B,
  ROUND(SUM(CASE WHEN IS_MP = 'Individual' THEN COALESCE(balance, 0) ELSE 0 END) / 1e9, 0) AS individual_B,
  ROUND(SUM(CASE WHEN IS_MP = 'Money Pool' THEN COALESCE(balance, 0) ELSE 0 END) / 1e9, 0) AS money_pool_B
FROM `momovn-prod.BU_FI.mart_ttt_daily_user_record`
WHERE GRASS_DATE IN (
  LAST_DAY(DATE '2025-01-01'), LAST_DAY(DATE '2025-02-01'), LAST_DAY(DATE '2025-03-01'),
  LAST_DAY(DATE '2025-04-01'), LAST_DAY(DATE '2025-05-01'), LAST_DAY(DATE '2025-06-01'),
  LAST_DAY(DATE '2025-07-01'), LAST_DAY(DATE '2025-08-01'), LAST_DAY(DATE '2025-09-01'),
  LAST_DAY(DATE '2025-10-01'), LAST_DAY(DATE '2025-11-01'), LAST_DAY(DATE '2025-12-01'),
  LAST_DAY(DATE '2026-01-01'), LAST_DAY(DATE '2026-02-01'),
  DATE '2026-03-09'
)
GROUP BY GRASS_DATE
ORDER BY GRASS_DATE
